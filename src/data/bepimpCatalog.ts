// Helper to extract unique keywords for interactive filtering chips
export const getAllBepimpKeywords = (): string[] => {
  const set = new Set<string>();
  bepimpCatalogData.forEach((item) => {
    item.keywords.forEach((kw) => set.add(kw.toUpperCase()));
  });
  return Array.from(set).sort();
};

// Helper to extract unique categories
export const getAllBepimpCategories = (): string[] => {
  const set = new Set<string>();
  bepimpCatalogData.forEach((item) => set.add(item.category));
  return Array.from(set).sort();
};
